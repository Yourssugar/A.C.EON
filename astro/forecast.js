/* ── детерминированный сид от даты+знака (стабилен в течение дня) ── */
function _h(s){ let x=2166136261>>>0; for(let i=0;i<s.length;i++){ x^=s.charCodeAt(i); x=Math.imul(x,16777619); } return x>>>0; }

/* ── главный генератор ──
   sunSign  — ключ знака ('aries'...)
   sky      — { moonSign, moonPhaseName, moonIllum, mercuryRetro }
   date     — Date (по умолчанию сегодня)                                     */
function dailyForecast(sunSign, sky, date = new Date()){
  const M = window.ASTRO_META;
  const dateKey = `${date.getFullYear()}-${date.getMonth()+1}-${date.getDate()}`;
  const seed = _h(dateKey + '|' + sunSign);
  const pick = (arr, salt) => arr[((_h(salt) ^ seed) >>> 0) % arr.length];

  const myEl = SIGN_ELEMENT[sunSign];
  const moonEl = SIGN_ELEMENT[sky.moonSign];
  const state = harmony(myEl, moonEl);                 // amplified | harmonious | tense

  // совместимость дня: знак дружественной стихии, выбранный сидом
  const compatSigns = ELEMENT_SIGNS[HARMONIOUS_ELEMENT[myEl]];
  const compat = compatSigns[((_h("compat") ^ seed) >>> 0) % compatSigns.length];

  const workText = sky.mercuryRetro
    ? pick(FORECAST.work[state],'work') + ' ' + FORECAST.mercuryRetro
    : pick(FORECAST.work[state],'work');

  return {
    title: `Гороскоп на сегодня · ${M.signs[sunSign].glyph} ${M.signs[sunSign].ru}`,
    intro: pick(FORECAST.mood[state], 'mood'),
    blocks: [
      { icon:'❤', label:'Любовь',   text: pick(FORECAST.love[state],  'love') },
      { icon:'💼', label:'Работа',   text: workText },
      { icon:'💰', label:'Деньги',   text: pick(FORECAST.money[state], 'money') },
      { icon:'🌿', label:'Здоровье', text: pick(FORECAST.health[state],'health') },
      { icon:'✦',  label:'Совет дня', text: pick(FORECAST.advice, 'advice') }
    ],
    extras: {
      moon: `${sky.moonPhaseName}, Луна в знаке ${M.signs[sky.moonSign].ru} (${sky.moonIllum}%)`,
      mercury: sky.mercuryRetro ? 'ретроградный ℞' : 'директный',
      compat: `${M.signs[compat].glyph} ${M.signs[compat].ru}`,
      luckyNumber: (((_h("num") ^ seed) >>> 0) % 99) + 1,
      luckyColor: pick(FORECAST.colors, 'color')
    },
    state
  };
}

