// огонь+воздух дружат, земля+вода дружат, крест — напряжение
function harmony(e1, e2){
  if (e1 === e2) return 'amplified';
  const friends = { fire:'air', air:'fire', earth:'water', water:'earth' };
  return friends[e1] === e2 ? 'harmonious' : 'tense';
}
