const TONE_TEXT = {
  'слияние':    'сливаются в одно и усиливают друг друга',
  'напряжение': 'тянут в разные стороны — источник и конфликта, и роста',
  'гармония':   'поддерживают друг друга легко и естественно',
  'вызов':      'трутся и подталкивают — напряжение, которое движет вперёд',
  'поддержка':  'дружат и открывают возможности, если приложить усилие'
};

function interpret(kind, payload) {
  const P = ASTRO_META.planets, S = ASTRO_META.signs, A = ASTRO_META.aspects, H = ASTRO_META.houses;

  if (kind === 'planetInSign') {
    const { planet, sign } = payload;
    if (planetInSign[`${planet}.${sign}`]) return planetInSign[`${planet}.${sign}`];
    const p = P[planet], s = S[sign];
    return `${p.glyph} ${p.ru} в знаке ${s.ru}: сфера «${p.sphere}» окрашивается стихией ${s.element} (${s.modality}).`;
  }

  if (kind === 'planetInHouse') {
    const { planet, house } = payload;
    if (planetInHouse[`${planet}.${house}`]) return planetInHouse[`${planet}.${house}`];
    return `${P[planet].ru} направляет «${P[planet].sphere}» в сферу ${house} дома — ${H[house].toLowerCase()}.`;
  }

  if (kind === 'aspect' || kind === 'synastry') {
    const { a, type, b } = payload;
    const table = (kind === 'synastry') ? synastry : aspects;
    const hit = table[`${a}.${type}.${b}`] || table[`${b}.${type}.${a}`];
    if (hit) return hit;
    const lead = (kind === 'synastry')
      ? `${P[a].ru} одного и ${P[b].ru} другого`
      : `${P[a].ru} и ${P[b].ru}`;
    return `${lead} ${TONE_TEXT[A[type].tone]} (${A[type].ru.toLowerCase()}). Сферы: «${P[a].sphere}» и «${P[b].sphere}».`;
  }

  return '—';
}

