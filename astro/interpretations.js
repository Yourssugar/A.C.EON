/* ============================================================================
   interpret() — ЕДИНАЯ ТОЧКА РАЗРЕШЕНИЯ
   Сюда стекается любой запрос текста. Если ключа нет в базе — отдаём осмысленный
   fallback, собранный из метаданных. (Если когда-нибудь захочешь подмешать
   ИИ на пустые ключи — это единственное место, куда это встроится.)
   ============================================================================ */
function interpret(kind, payload) {
  const P = ASTRO_META.planets, S = ASTRO_META.signs, A = ASTRO_META.aspects;

  if (kind === 'planetInSign') {
    const { planet, sign } = payload;
    const key = `${planet}.${sign}`;
    if (planetInSign[key]) return planetInSign[key];
    // fallback из метаданных
    const p = P[planet], s = S[sign];
    return `${p.glyph} ${p.ru} в знаке ${s.ru} (${s.element}, ${s.modality}). ` +
           `Сфера «${p.sphere}» окрашивается стихией ${s.element}. — текст в базе пока не заполнен.`;
  }

  if (kind === 'planetInHouse') {
    const { planet, house } = payload;
    const key = `${planet}.${house}`;
    if (planetInHouse[key]) return planetInHouse[key];
    return `${P[planet].ru} в ${house} доме — сфера «${ASTRO_META.houses[house]}».`;
  }

  if (kind === 'aspect' || kind === 'synastry') {
    const { a, type, b } = payload;
    const table = (kind === 'synastry') ? synastry : aspects;
    // аспект симметричен: пробуем оба порядка
    return table[`${a}.${type}.${b}`] || table[`${b}.${type}.${a}`] ||
      `${P[a].ru} ${A[type].glyph} ${P[b].ru} — ${A[type].ru.toLowerCase()} (${A[type].tone}). — текст в базе пока не заполнен.`;
  }

  return '—';
}

