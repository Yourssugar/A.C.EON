/* случайные числа по зерну: одинаковое зерно, одинаковая раскладка */
function rng(seed){
  var a=seed|0;
  return function(){a=(a+0x6D2B79F5)|0;var t=Math.imul(a^(a>>>15),1|a);t=(t+Math.imul(t^(t>>>7),61|t))^t;return ((t^(t>>>14))>>>0)/4294967296;};
}

/* бесконечный режим: уровень n; симметричная раскладка, с номером растут ряды, прочность и особые кирпичи */
function endless(n,seed){
  var r=rng((seed||7)*1000+n*7919),rows=Math.min(11,4+Math.floor(n/2)),out=['............'];
  var pool=['1','1','2'];
  if(n>=2)pool.push('2','3');
  if(n>=3)pool.push('S','X');
  if(n>=5)pool.push('M','$');
  if(n>=6)pool.push('R','3');
  if(n>=8)pool.push('D','N','X');
  if(n>=10)pool.push('R','S','3');
  var gates=n>=7&&r()<0.35,portal=n>=6&&r()<0.3;
  var style=Math.floor(r()*4);
  for(var i=0;i<rows;i++){
    var half='';
    var moving=(pool.indexOf('M')>=0&&r()<0.12);
    for(var c=0;c<6;c++){
      var ch=pool[Math.floor(r()*pool.length)];
      if(style===1&&(i+c)%2)ch='.';
      if(style===2&&c===5-i%6)ch='.';
      if(style===3&&i%3===2)ch=c%2?'S':'.';
      if(ch==='M'||ch==='N')ch='2';
      if(r()<0.08)ch='.';
      half+=ch;
    }
    var row=half+half.split('').reverse().join('');
    if(moving)row='M'+'...........';
    out.push(row);
  }
  if(gates){out.splice(1,0,'GGGGGGGGGGGG');out.push('.....KK.....');}
  if(portal){out.push('P..........Q');}
  /* все кирпичи должны быть достижимы: если сталь где-то замуровала кирпичи, она становится обычной */
  if(unreachable(out))out=out.map(function(row){return row.replace(/S/g,'3');});
  /* не меньше пяти разбиваемых кирпичей */
  var cnt=out.join('').replace(/[.SGPQ]/g,'').length;
  if(cnt<5)out.push('222222222222');
  return out.map(function(s){return (s+'............').slice(0,12);});
}

/* есть ли кирпичи, до которых мяч не доберётся: поиск в ширину от низа поля через клетки,
   которые не сталь (ворота открываются, если достижим переключатель; порталы связаны) */
function unreachable(rows){
  var R=rows.length+6,C=12,g=[],r,c;
  for(r=0;r<R;r++)g.push((rows[r]||'............').split(''));
  function flood(open){
    var seen={},q=[[R-1,0]],P=null,Q=null;seen[(R-1)+',0']=1;
    for(r=0;r<R;r++)for(c=0;c<C;c++){if(g[r][c]==='P')P=[r,c];if(g[r][c]==='Q')Q=[r,c];}
    while(q.length){
      var cur=q.pop(),a=cur[0],b=cur[1],ch=g[a][b];
      var nb=[[a+1,b],[a-1,b],[a,b+1],[a,b-1]];
      if(ch==='P'&&Q)nb.push(Q);if(ch==='Q'&&P)nb.push(P);
      nb.forEach(function(n){
        var x=n[0],y=n[1];if(x<0||x>=R||y<0||y>=C)return;
        var k=x+','+y,h=g[x][y];
        if(seen[k]||h==='S'||(h==='G'&&!open))return;
        seen[k]=1;q.push([x,y]);
      });
    }
    return seen;
  }
  var s=flood(false),k=false;
  for(r=0;r<R;r++)for(c=0;c<C;c++)if(g[r][c]==='K'&&s[r+','+c])k=true;
  if(k)s=flood(true);
  for(r=0;r<R;r++)for(c=0;c<C;c++)if('.SGPQ'.indexOf(g[r][c])<0&&!s[r+','+c])return true;
  return false;
}

/* стена для режима «На время»: один ряд, тем прочнее, чем дальше по времени */
function timeRow(k,seed){
  var r=rng((seed||3)*99+k*131),row='';
  for(var c=0;c<12;c++){
    var x=r(),ch;
    if(x<0.08)ch='.';
    else if(x<0.14)ch='X';
    else if(x<0.18)ch='$';
    else if(x<0.18+Math.min(0.35,k*0.02))ch='3';
    else if(x<0.55)ch='2';
    else ch='1';
    row+=ch;
  }
  return row;
}

